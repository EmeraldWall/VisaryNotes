"""Generates platform files from tokens.json and themes.json.

Usage: python3 tools/design/generate.py [output folder]
With no folder, writes straight into the app (src/VisaryNotes.App) and keeps a
copy of every file in tools/design/generated for review.
Writes:
* Tokens.xaml     MAUI ResourceDictionary with spacing, size, radius and type (x:Double, Thickness)
* dimens.xml      Android dimension resources for home screen widgets
* tokens.css      CSS variables for the document viewer and design prototypes
* Theme.<name>.xaml one MAUI ResourceDictionary of colours per theme

Edit the JSON, never the generated files.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
tokens = json.load(open(os.path.join(HERE, 'tokens.json')))
themes = json.load(open(os.path.join(HERE, 'themes.json')))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'generated')
os.makedirs(out, exist_ok=True)
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
APP_STYLES = os.path.join(ROOT, 'src', 'VisaryNotes.App', 'Resources', 'Styles', 'Generated')
APP_VALUES = os.path.join(ROOT, 'src', 'VisaryNotes.App', 'Platforms', 'Android', 'Resources', 'values')


def inset(spec):
    parts = [tokens['space'][p] for p in spec.split()]
    if len(parts) == 1:
        parts = parts * 4
    elif len(parts) == 2:
        parts = [parts[0], parts[1], parts[0], parts[1]]
    top, right, bottom, left = parts
    return f'{left},{top},{right},{bottom}'

HEADER = 'Generated by tools/design/generate.py from tokens.json. Do not edit.'


def pascal(name):
    return ''.join(p.capitalize() for p in name.replace('_', '-').split('-'))


def flat_numbers():
    for group in ('space', 'size', 'radius', 'border'):
        for k, v in tokens[group].items():
            yield k, v


# MAUI tokens
x = ['<?xml version="1.0" encoding="utf-8" ?>', f'<!-- {HEADER} -->',
     '<ResourceDictionary xmlns="http://schemas.microsoft.com/dotnet/2021/maui"',
     '                    xmlns:x="http://schemas.microsoft.com/winfx/2009/xaml">']
for k, v in flat_numbers():
    x.append(f'    <x:Double x:Key="{pascal(k)}">{v}</x:Double>')
for k, v in tokens['space'].items():
    x.append(f'    <Thickness x:Key="Pad{pascal(k)}">{v}</Thickness>')
for k, spec in tokens.get('insets', {}).items():
    if not k.startswith('_'):
        x.append(f'    <Thickness x:Key="Inset{pascal(k)}">{inset(spec)}</Thickness>')
for k, ref in tokens['layout'].items():
    x.append(f'    <x:Double x:Key="Layout{pascal(k)}">{tokens["space"][ref]}</x:Double>')
for k, t in tokens['type'].items():
    x.append(f'    <x:Double x:Key="Font{pascal(k)}">{t["size"]}</x:Double>')
    x.append(f'    <x:Double x:Key="Line{pascal(k)}">{t["line"]}</x:Double>')
for k, v in tokens['glass'].items():
    if isinstance(v, (int, float)):
        x.append(f'    <x:Double x:Key="Glass{pascal(k)}">{v}</x:Double>')
x.append('</ResourceDictionary>')
open(os.path.join(out, 'Tokens.xaml'), 'w').write('\n'.join(x) + '\n')

# Android widget dimensions
d = ['<?xml version="1.0" encoding="utf-8"?>', f'<!-- {HEADER} -->', '<resources>']
for k, v in flat_numbers():
    d.append(f'    <dimen name="vn_{k.replace("-", "_")}">{v}dp</dimen>')
for k, t in tokens['type'].items():
    d.append(f'    <dimen name="vn_text_{k}">{t["size"]}sp</dimen>')
d.append('</resources>')
open(os.path.join(out, 'dimens.xml'), 'w').write('\n'.join(d) + '\n')

# CSS variables
c = [f'/* {HEADER} */', ':root {']
for k, v in flat_numbers():
    c.append(f'  --{k}: {v}px;')
for k, t in tokens['type'].items():
    c.append(f'  --fs-{k}: {t["size"]}px;')
    c.append(f'  --lh-{k}: {t["line"]}px;')
for k, v in tokens['glass'].items():
    if isinstance(v, (int, float)):
        c.append(f'  --glass-{k}: {v};')
c.append('}')
open(os.path.join(out, 'tokens.css'), 'w').write('\n'.join(c) + '\n')

# Theme colour dictionaries
for name, t in themes.items():
    lines = ['<?xml version="1.0" encoding="utf-8" ?>', f'<!-- {HEADER} Theme: {name} -->',
             '<ResourceDictionary xmlns="http://schemas.microsoft.com/dotnet/2021/maui"',
             '                    xmlns:x="http://schemas.microsoft.com/winfx/2009/xaml">']
    for k, v in t.items():
        if isinstance(v, str) and v.startswith('#'):
            lines.append(f'    <Color x:Key="{pascal(k)}">{v}</Color>')
    lines.append('</ResourceDictionary>')
    open(os.path.join(out, f'Theme.{name.replace(" ", "")}.xaml'), 'w').write('\n'.join(lines) + '\n')

if len(sys.argv) == 1 and os.path.isdir(os.path.dirname(APP_STYLES)):
    import shutil
    os.makedirs(APP_STYLES, exist_ok=True)
    shutil.copy(os.path.join(out, 'Tokens.xaml'), os.path.join(APP_STYLES, 'Tokens.xaml'))
    os.makedirs(APP_VALUES, exist_ok=True)
    shutil.copy(os.path.join(out, 'dimens.xml'), os.path.join(APP_VALUES, 'vn_dimens.xml'))
    print(f'Copied Tokens.xaml and vn_dimens.xml into the app')

print(f'Wrote tokens and {len(themes)} themes to {out}')
